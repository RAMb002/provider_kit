/// {@template provider_kit.async_view_state_notifier_base.intro}
/// Internal implementation shared by [FutureNotifier] and [StreamNotifier].
///
/// [_AsyncViewStateNotifierBase] provides the managed asynchronous execution
/// infrastructure used by ProviderKit's built-in asynchronous notifiers.
///
/// It coordinates build operations, protects against outdated operations
/// updating the current state, and manages shared state transitions,
/// refreshes, rebuilds, and disposal.
///
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.constructors_param}
/// ### Constructor options
///
/// - [initialState]: The initial state. When omitted, defaults to
///   [LoadingState] if [startInitialBuild] is enabled, or [InitialState] otherwise.
/// - [startInitialBuild]: Whether to start the initial build automatically.
///   Defaults to `true`. Set to `false` to control when the first build
///   starts manually.
/// - [enableEmptyState]: Whether an emitted empty [Iterable] should produce
///   [EmptyState]. Defaults to `true`. When `false`, empty iterables are
///   published as [DataState].
/// - [loadingMessage]: Optional message for loading states generated by
///   this notifier.
/// - [emptyMessage]: Optional message for empty states generated by
///   this notifier.
///
/// When [startInitialBuild] is `false`, call [refresh] or [rebuild] to start
/// the initial build manually.
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.state_handling}
/// ### State handling
///
/// Asynchronous notifiers manage loading, data, empty, and error states
/// according to their build results and lifecycle:
///
/// - Successful results can be represented as [DataState].
/// - Empty results can be represented as [EmptyState], unless
///   [enableEmptyState] is `false`.
/// - When usable data is unavailable, a build failure transitions the state
///   to [ErrorState].
/// - When existing data can be preserved, a failure can be reported without
///   replacing that data with [ErrorState].
///
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.state_messages}
/// ### State messages
///
/// You can provide optional [loadingMessage] and [emptyMessage] values
/// through the constructor to configure the default messages for loading
/// and empty states generated by this notifier.
///
/// These messages are state metadata. When displayed by ProviderKit's
/// view-state widgets, they are resolved using the configured
/// `ViewStateWidgetsProvider.messageResolver` intended for localization.
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.error_handling}
/// ### Error handling
///
/// Errors are handled according to the concrete notifier's lifecycle and
/// whether existing data can be preserved. Errors that replace the current
/// state are represented by [ErrorState]. Errors that occur while preserving
/// existing data are reported through the inherited notifier error-handling
/// mechanism without necessarily changing the current [ViewState].
///
/// The behavior of the returned [Future] depends on the operation and the
/// concrete notifier. A future-based build failure can be propagated to the
/// caller, while errors emitted later by a stream generally cannot be
/// propagated through the [StreamNotifier.refresh] future.
///
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.about}
/// ### Retry and refresh behavior
///
/// When an asynchronous notifier is used with a view-state widget, retry
/// and refresh handling follows these rules:
///
/// 1. An explicitly provided [ErrorState.onRetry] or [EmptyState.onRefresh]
///    callback takes precedence.
/// 2. If the corresponding state callback is `null`, supported widgets fall
///    back to the notifier's [refresh] method.
///
/// The default callbacks generated by asynchronous notifiers invoke
/// [refresh] without awaiting its returned future and ignore its errors.
/// This makes them suitable for UI event handlers, such as retry and refresh
/// buttons.
///
/// This behavior applies to [ViewStateBuilder], [ViewStateBuilder.multi],
/// [ViewStateListener], [ViewStateListener.multi], [ViewStateConsumer], and
/// [ViewStateConsumer.multi].
///
/// ### Refreshing
///
/// [refresh] refreshes data according to the concrete notifier's
/// implementation:
///
/// - [FutureNotifier] reruns its build workflow. Existing data is preserved
///   while refreshing when available. Otherwise, the notifier can transition
///   to [LoadingState] while loading initial data.
/// - [StreamNotifier] restarts its stream subscription while preserving
///   existing data when available.
///
/// The returned future follows the relevant asynchronous operation. When an
/// operation is superseded, callers waiting for it follow its replacement.
/// Errors from outdated operations are ignored, while errors from the latest
/// relevant operation can be propagated to the caller.
///
/// Refreshing or rebuilding invalidates previously captured staleness checks.
/// These checks prevent outdated asynchronous work from continuing to act on
/// the current state, but do not cancel the underlying work automatically.
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.state_setters}
/// ### Manually setting states
///
/// Subclasses can use the state-setting helpers to update the current
/// [ViewState] while preserving ProviderKit's default behavior:
///
/// - [setInitial] sets the initial state.
/// - [setLoading] sets a loading state using the configured default message
///   unless an override is provided. An optional progress value can represent
///   progress within a multi-stage operation.
/// - [setData] publishes the supplied data through [DataState].
/// - [setEmpty] sets an empty state using the configured default message and
///   provides a callback that refreshes the notifier.
/// - [setError] sets an error state using the configured error-info mapping
///   and provides a callback that refreshes the notifier. The error is also
///   dispatched to the NotifierObserver.
///
/// These helpers do nothing after the notifier has been disposed.
/// {@endtemplate}
///
/// {@template provider_kit.async_view_state_notifier_base.check_staleness}
/// ### Protect other asynchronous operations
///
/// State assignments inside [build] are already protected against outdated
/// builds. For independent asynchronous methods, use [checkStaleness] to
/// detect when a refresh, rebuild, explicit build invalidation, or disposal
/// has made the operation outdated:
///
/// ```dart
/// Future<void> loadNextPage() async {
///   final isStale = checkStaleness();
///
///   final products = await _repository.fetchNextPage();
///
///   if (isStale()) return;
///
///   state = DataState([...state.data, ...products]);
/// }
/// ```
///
/// Check the staleness callback after asynchronous gaps before continuing work
/// or updating state. This doesn't cancel an in-flight request; it lets you
/// stop subsequent work when the operation becomes outdated.
///
/// The staleness check becomes invalid when the notifier is refreshed, rebuilt,
/// explicitly invalidated, or disposed.
/// {@endtemplate}

sealed class _AsyncViewStateNotifierBase<T> extends AsyncViewStateNotifier<T> {
  _AsyncViewStateNotifierBase({
    ViewState<T>? initialState,
    bool startInitialBuild = true,
    bool enableEmptyState = true,
    this.loadingMessage,
    this.emptyMessage,
  }) : _shouldStartInitialBuild = startInitialBuild,
       // ignore: prefer_initializing_formals
       _enableEmptyState = enableEmptyState,
       super(
         initialState:
             initialState ??
             (startInitialBuild
                 ? LoadingState<T>(loadingMessage)
                 : InitialState<T>()),
       ) {
    _buildManager.bindOperationInvalidator(_invalidateStateScopes);
  }

  final bool _shouldStartInitialBuild;

  /// Whether empty results should be represented as [DataState].
  final bool _enableEmptyState;

  /// The default message for loading states produced by this notifier,
  /// including the initial state and subsequent loading states during
  /// rebuilds.
  ///
  /// Subclasses can reuse this value when manually creating a
  /// [LoadingState].
  @protected
  final String? loadingMessage;

  /// The configured message for empty asynchronous results.
  ///
  /// Subclasses can reuse this value when manually setting an empty state.
  @protected
  final String? emptyMessage;

  final AsyncBuildManager _buildManager = AsyncBuildManager();

  /// A unique Zone key for state assignments made during a managed build.
  final Object _buildZoneKey = Object();

  /// Tracks the validity of independent asynchronous operations.
  final GenerationGuard _generationGuard = GenerationGuard();

  /// Starts the initial managed build after the public initialization
  /// lifecycle has been invoked.
  ///
  /// This hook is called by [AsyncViewStateNotifier] and ensures that
  /// built-in asynchronous notifiers begin their initial build only after
  /// user-defined initialization has been attempted.
  @override
  void _afterInitialize() {
    if (_shouldStartInitialBuild) {
      _startInitialBuild();
    }
  }

  /// Schedules the initial build through [AsyncBuildManager].
  void _startInitialBuild() {
    _buildManager.startInitial(_runBuild).ignore();
  }

  /// Runs the subclass's build lifecycle in an isolated Zone.
  ///
  /// Framework-managed state transitions must not inherit a generation token
  /// from an enclosing build or asynchronous callback.
  Future<void> _runBuild(int token, AsyncBuildReason reason) {
    return runZoned<Future<void>>(
      () => _executeBuild(token, reason),
      zoneValues: {_buildZoneKey: null},
    );
  }

  /// Implements the lifecycle specific to a Future- or Stream-based notifier.
  Future<void> _executeBuild(int token, AsyncBuildReason reason);

  /// Applies the default loading-state policy before executing a build.
  void _prepareBuild(AsyncBuildReason reason) {
    final currentState = state;

    // Initial builds and refreshes preserve existing data.
    final preserveData =
        reason != AsyncBuildReason.rebuild && currentState.isData;

    // Preserve a custom loading state supplied as the initial state.
    final preserveInitialLoading =
        reason == AsyncBuildReason.initial && currentState.isLoading;

    if (preserveData || preserveInitialLoading) return;

    final loadingState = LoadingState<T>(loadingMessage);

    if (currentState != loadingState) {
      state = loadingState;
    }
  }

  /// Whether [token] still belongs to the active build generation.
  bool _isCurrentBuild(int token) {
    return mounted && _buildManager.isCurrent(token);
  }

  /// Whether [value] represents an empty result under the configured policy.
  bool _isEmptyState(Object? value) {
    return _enableEmptyState && value is Iterable && value.isEmpty;
  }

  /// Schedules a rebuild using the latest inputs.
  ///
  /// Multiple requests made before a pending rebuild starts are coalesced
  /// into a single operation using the latest inputs.
  ///
  /// If the operation being awaited becomes outdated, the returned future
  /// follows its replacement until the latest relevant operation completes.
  ///
  /// Errors from outdated operations are ignored. If the latest relevant
  /// operation fails, the returned future propagates its original error
  /// and stack trace.
  @override
  @protected
  @nonVirtual
  Future<void> rebuild() {
    final operation = _buildManager.rebuild(_runBuild);

    // Callers may await the original future to observe its error.
    operation.ignore();

    return operation;
  }

  /// Invalidates the current build without starting a replacement.
  ///
  /// Pending and running build operations become outdated. Their results
  /// and state assignments are ignored.
  ///
  /// For [StreamNotifier], the active stream subscription is also cancelled.
  ///
  /// This method does not change the current [ViewState]. Use [setInitial]
  /// or another state-setting method when a state reset is required.
  ///
  /// Unlike [rebuild], this method does not schedule another build.
  @override
  @protected
  @nonVirtual
  void invalidateBuild() {
    if (!mounted) return;

    _buildManager.invalidate();
    _invalidateBuildResources();
  }

  /// Releases resources associated with the current build when it is invalidated.
  ///
  /// Overridden by built-in notifiers that own build-specific resources.
  void _invalidateBuildResources() {}

  /// Refreshes data using the current inputs.
  ///
  /// If a rebuild is pending or a valid build is running, waits for that
  /// operation. If it becomes outdated while waiting, follows its
  /// replacement. Otherwise, starts a new refresh operation.
  ///
  /// Existing data remains available while refreshing. If the latest
  /// relevant operation fails, the returned future propagates its original
  /// error and stack trace, even when existing data is preserved.
  @override
  @mustCallSuper
  Future<void> refresh() {
    if (!mounted) return Future<void>.value();

    final operation = _buildManager.refresh(_runBuild);

    // Also support callers that intentionally do not await refresh.
    operation.ignore();

    return operation;
  }

  /// Publishes a state only when its managed build is still current.
  ///
  /// The generation token is cleared during listener notification so callbacks
  /// do not accidentally inherit the generation of the originating build.
  @override
  @nonVirtual
  set state(ViewState<T> newState) {
    final token = Zone.current[_buildZoneKey];

    if (token is! int) {
      super.state = newState;
      return;
    }

    if (!_isCurrentBuild(token)) return;

    runZoned<void>(
      () => super.state = newState,
      zoneValues: {_buildZoneKey: null},
    );
  }

  /// Returns a callback that checks whether an asynchronous operation
  /// has become outdated.
  ///
  /// Capture the callback before starting work and check it after each
  /// [await], before continuing work or updating state.
  ///
  /// A refresh, rebuild, or disposal can invalidate the captured operation.
  /// This does not cancel in-flight asynchronous work.
  ///
  /// Example:
  ///
  /// ```dart
  /// Future<void> loadNextPage() async {
  ///   final isStale = checkStaleness();
  ///
  ///   final products = await _repository.fetchNextPage();
  ///
  ///   if (isStale()) return;
  ///
  ///   state = DataState([...state.data, ...products]);
  /// }
  /// ```
  @override
  @protected
  @nonVirtual
  bool Function() checkStaleness() {
    final generation = _generationGuard.currentGenerationToken;

    return () {
      return !mounted || !_generationGuard.isCurrent(generation);
    };
  }

  /// Sets the current state to [InitialState].
  @override
  @protected
  @nonVirtual
  void setInitial() {
    if (!mounted) return;
    state = InitialState<T>();
  }

  /// Sets the current state to [LoadingState].
  ///
  /// Uses [message] when provided, or [loadingMessage] otherwise.
  /// The optional [progress] value is passed to the loading state.
  @override
  @protected
  @nonVirtual
  void setLoading({String? message, double? progress}) {
    if (!mounted) return;
    state = LoadingState<T>(message ?? loadingMessage, progress);
  }

  /// Sets the current state to [DataState] with the provided [data].
  @override
  @protected
  @nonVirtual
  void setData(T data) {
    if (!mounted) return;
    state = DataState<T>(data);
  }

  /// Sets the current state to [EmptyState].
  ///
  /// Uses [message] when provided, or [emptyMessage] otherwise.
  /// The state receives a default refresh callback that invokes [refresh].
  @override
  @protected
  @nonVirtual
  void setEmpty([String? message]) {
    if (!mounted) return;
    state = EmptyState<T>(message ?? emptyMessage, _refreshIgnoringErrors);
  }

  /// Sets the current state to [ErrorState] for the provided [error] and
  /// [stackTrace].
  ///
  /// Error information is resolved using the configured `ErrorInfoMapper`.
  /// The state receives a default retry callback that invokes [refresh].
  /// The error is also dispatched to the [NotifierObserver].
  @override
  @protected
  @nonVirtual
  void setError(Object error, StackTrace stackTrace) {
    if (!mounted || _isInStaleBuildZone()) return;
    state = ErrorState<T>(error, stackTrace, onRetry: _refreshIgnoringErrors);
    if (!mounted) return;
    dispatchError(error, stackTrace);
  }

  void _refreshIgnoringErrors() {
    refresh().ignore();
  }

  bool _isInStaleBuildZone() {
    final token = Zone.current[_buildZoneKey];
    return token is int && !_isCurrentBuild(token);
  }

  /// Invalidates all checks captured before this call.
  void _invalidateStateScopes() {
    _generationGuard.next();
  }

  /// Releases resources owned by a specialized async notifier.
  ///
  /// Subclasses can override this internal hook for resources such as stream
  /// subscriptions. The manager is invalidated before this hook is called.
  void _disposeAsyncResources() {}

  @mustCallSuper
  @override
  void dispose() {
    _buildManager.dispose();

    // Keep the existing scope guard and invalidate it during disposal.
    _generationGuard.invalidate();

    _disposeAsyncResources();

    super.dispose();
  }
}
